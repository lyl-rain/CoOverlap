#!/usr/bin/env python3
"""Rebuild SOURCE_VERIFICATION.json and FREEZE.json for the B8 preparation.

Read-only with respect to deployment, prediction and frozen inputs.  Run after
changing a planning document; the deployment manifest itself is generated by
`deployment/DEPLOY_SHA256.txt` and must be regenerated separately if a
deployment file changes.
"""
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent
DEP = HERE / 'deployment'
sys.path.insert(0, str(DEP))
import m3_b8_plan as b8  # noqa: E402


def sha(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def entry(role, path):
    p = Path(path)
    return dict(role=role, path=str(p), sha256=sha(p), bytes=p.stat().st_size)


def main():
    dep_files = []
    for p in sorted(DEP.rglob('*')):
        if p.is_file() and p.name != 'DEPLOY_SHA256.txt' and '__pycache__' not in p.parts:
            dep_files.append(entry(str(p.relative_to(DEP)), p))
    docs = {name: entry(name, HERE / name) for name in (
        'README.md', 'REUSE_AND_DIFF.md', 'MINIMAL_DIFF.patch', 'GPU_PLAN.md',
        'APPROVAL_CHECKLIST.md', 'RESULTS_TEMPLATE.json', 'BUDGET.json',
        'FAIRNESS_CHECK.json', 'prediction/EVALUATION_PROTOCOL.md',
        'build_manifests.py')}
    frozen = {
        'b4_result': entry('b4_result', ROOT/'reports/m3_b2/20261021/split_priority_ablation_v1_r2/gpu_run_01/board/run_01/model/result.json'),
        'b4_config': entry('b4_config', ROOT/'reports/m3_b2/20261021/split_priority_ablation_v1_r2/deployment/CONFIG.json'),
        'b4_executor': entry('b4_executor', ROOT/'reports/m3_b2/20261021/split_priority_ablation_v1_r2/deployment/m2_executor.py'),
        'b5_manifest': entry('b5_manifest', ROOT/'reports/m3_b2/20261021/boundary_budget_anchors_v1_r1/deployment/DEPLOY_SHA256.txt'),
        'b7_manifest': entry('b7_manifest', ROOT/'reports/m3_b2/20261021/stage_startup_b7_v1/deployment/DEPLOY_SHA256.txt'),
        'r1_freeze': entry('r1_freeze', ROOT/'reports/m3_b2/20261022/empirical_plan_selector_v1_r1/freeze/FREEZE.json'),
        'r1_costs': entry('r1_costs', ROOT/'reports/m3_b2/20261022/empirical_plan_selector_v1_r1/freeze/TRAIN_COSTS.json'),
        'r1_rules': entry('r1_rules', ROOT/'reports/m3_b2/20261022/empirical_plan_selector_v1_r1/freeze/RULES.json'),
        'r1_model': entry('r1_model', ROOT/'reports/m3_b2/20261022/empirical_plan_selector_v1_r1/selector/plan_model.py'),
        'prediction': entry('prediction', HERE/'prediction/PREDICTION.json'),
        'prediction_receipt': entry('prediction_receipt', HERE/'prediction/PREDICTION_RECEIPT.json'),
        'prediction_md': entry('prediction_md', HERE/'prediction/PREDICTION.md'),
        'prediction_script': entry('prediction_script', HERE/'prediction/predict_b8.py'),
        'cpu_results': entry('cpu_results', DEP/'CPU_RESULTS.json'),
        'cpu_tests': entry('cpu_tests', DEP/'CPU_TESTS.log'),
    }
    sv = dict(
        schema='m3_b8_split_budget_source_verification_v1',
        status='PREPARED_NOT_APPROVED_NOT_RUN', protocol=b8.PROTOCOL,
        deployment=dict(base=str(DEP), manifest=str(DEP/'DEPLOY_SHA256.txt'),
                        manifest_sha256=sha(DEP/'DEPLOY_SHA256.txt'),
                        file_count=len(dep_files), files=dep_files),
        prediction=dict(json=str(HERE/'prediction/PREDICTION.json'),
                        sha256=sha(HERE/'prediction/PREDICTION.json'),
                        receipt=str(HERE/'prediction/PREDICTION_RECEIPT.json'),
                        receipt_sha256=sha(HERE/'prediction/PREDICTION_RECEIPT.json'),
                        evaluation_protocol=docs['prediction/EVALUATION_PROTOCOL.md']),
        docs=docs, frozen=frozen,
        no_model=True, no_worker=True, no_ssh=True, no_deploy=True,
        no_scope=True, no_hardware_write=True,
        note='Local preparation only. The deployment package has not been copied or executed on the board.')
    (HERE/'SOURCE_VERIFICATION.json').write_text(json.dumps(sv, indent=2, sort_keys=True)+'\n')
    freeze = dict(
        schema='m3_b8_split_budget_freeze_v1',
        status='PREPARED_NOT_APPROVED_NOT_RUN', protocol=b8.PROTOCOL,
        approval_required='new explicit M3 split x budget challenge GPU and five-node scope approval',
        approval_requested=True, no_run=True,
        config=dict(path=str(DEP/'CONFIG.json'), sha256=sha(DEP/'CONFIG.json')),
        deploy=dict(path=str(DEP/'DEPLOY_SHA256.txt'), sha256=sha(DEP/'DEPLOY_SHA256.txt'),
                    file_count=len(dep_files)),
        prediction=dict(path=str(HERE/'prediction/PREDICTION.json'),
                        sha256=sha(HERE/'prediction/PREDICTION.json'),
                        receipt_sha256=sha(HERE/'prediction/PREDICTION_RECEIPT.json'),
                        evaluation_protocol_sha256=docs['prediction/EVALUATION_PROTOCOL.md']['sha256'],
                        status=json.loads((HERE/'prediction/PREDICTION.json').read_text())['status']),
        cpu=dict(path=str(DEP/'CPU_RESULTS.json'), sha256=sha(DEP/'CPU_RESULTS.json')),
        budget=dict(path=str(HERE/'BUDGET.json'), sha256=sha(HERE/'BUDGET.json')),
        fairness=dict(path=str(HERE/'FAIRNESS_CHECK.json'), sha256=sha(HERE/'FAIRNESS_CHECK.json')),
        docs={k: v['sha256'] for k, v in docs.items()},
        source=dict(r1_freeze=frozen['r1_freeze'], r1_costs=frozen['r1_costs'],
                    r1_rules=frozen['r1_rules'], r1_model=frozen['r1_model'],
                    b4_executor=frozen['b4_executor']),
        manifest_self_hash='not included by design',
        boundary='consistency relative to the specified package/prediction; not tamper-proof'
                 ' authentication or a proof of execution order',
        no_model=True, no_worker=True, no_ssh=True, no_deploy=True,
        no_scope=True, no_hardware_write=True)
    (HERE/'FREEZE.json').write_text(json.dumps(freeze, indent=2, sort_keys=True)+'\n')
    print(json.dumps(dict(source_verification_sha256=sha(HERE/'SOURCE_VERIFICATION.json'),
                          freeze_sha256=sha(HERE/'FREEZE.json'),
                          deployment_sha256=sha(DEP/'DEPLOY_SHA256.txt'),
                          docs=len(docs), deployment_files=len(dep_files)), indent=2))


if __name__ == '__main__':
    main()
