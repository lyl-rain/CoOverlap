#!/usr/bin/env python3
"""Write CPU_PATHS.md: the readable outcome of the evaluation entry on four paths.

Paths: normal 8/8, 5 executed + 3 real NOT_STARTED, all 8 NOT_STARTED, and a
condition mismatch (same label, different phase).  All fixtures are synthetic and
marked ``fixture: true``; no B9 measurement exists.
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
B9 = HERE.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(B9 / 'analysis'))
sys.path.insert(0, str(B9 / 'prediction'))

import fixture_b9 as fx          # noqa: E402
import evaluate_b9 as ev        # noqa: E402

RULES = B9.parent / 'expert_reserve_selector_v1_r1' / 'RULES.json'
COSTS = B9.parent / 'expert_reserve_selector_v1_r1' / 'COSTS.json'
PRED = B9 / 'prediction' / 'PREDICTION.json'
SEL = B9 / 'prediction' / 'SELECTION_FREEZE.json'


def cfg_copy(tmp):
    cfg = json.loads((B9 / 'deployment' / 'CONFIG.json').read_text())
    cfg['prediction']['sha256'] = fx.sha(PRED)
    cfg['selection']['sha256'] = fx.sha(SEL)
    cfg['selection']['rule_sha256'] = fx.sha(RULES)
    cfg['selection']['costs_sha256'] = fx.sha(COSTS)
    cfg['analysis_modules'] = {'evaluate_b9.py': fx.sha(B9 / 'analysis' / 'evaluate_b9.py'),
                               'prediction_model.py': fx.sha(B9 / 'prediction' / 'prediction_model.py')}
    path = Path(tmp) / 'CONFIG.json'
    path.write_text(json.dumps(cfg, indent=2, sort_keys=True) + '\n')
    return cfg, path


def run(cfg, cfg_path, tmp, name, **kw):
    result = fx.build(cfg, cfg_path, PRED, SEL, **kw)
    rpath = Path(tmp) / (name + '.json')
    fx.write(rpath, result)
    out = Path(tmp) / (name + '_out')
    code = ev.main(['--result', str(rpath), '--out', str(out), '--config', str(cfg_path),
                    '--rules', str(RULES), '--costs', str(COSTS),
                    '--prediction', str(PRED), '--selection', str(SEL)])
    return code, json.loads((out / 'EVALUATION.json').read_text())


def row(name, code, doc):
    t = doc['part_b_official_performance']['totals']
    c = doc['part_c_selection']
    fmt = lambda d: '/'.join('%s=%d' % (k, d[k]) for k in ('PASS', 'FAIL', 'UNCERTAIN',
                                                           'INCOMPLETE', 'INVALID') if d[k])
    return '| %s | %d | %s | %s | %s | %s | %s | %s |' % (
        name, code, doc['verdict'], c['condition']['status'], c['prediction_status'],
        fmt(t['Expert']), fmt(t['Refresh']),
        '%d/%d/%d' % (c['reserve']['short'], c['reserve']['unknown'], c['reserve']['total']))


def main():
    with tempfile.TemporaryDirectory() as tmp:
        cfg, cfg_path = cfg_copy(tmp)
        rows = [row('normal 8/8', *run(cfg, cfg_path, tmp, 'normal')),
                row('5 executed + 3 NOT_STARTED', *run(cfg, cfg_path, tmp, 'stopped', executed=5)),
                row('all 8 NOT_STARTED', *run(cfg, cfg_path, tmp, 'none', executed=0))]
        bad = json.loads(json.dumps(cfg))
        bad['phase_ns'] = 20_000_000
        bad_path = Path(tmp) / 'CONFIG_bad.json'
        bad_path.write_text(json.dumps(bad, indent=2, sort_keys=True) + '\n')
        rows.append(row('condition mismatch', *run(bad, bad_path, tmp, 'mismatch')))
    doc = '\n'.join([
        '# CPU path summary — B9-r2 evaluation entry (fixtures only)',
        '',
        'Generated by `tests/path_summary.py`.  All results are synthetic fixtures',
        '(`fixture: true`); none is a B9 measurement and none is a GPU result.',
        '',
        '| path | exit | verdict | condition | prediction | Expert | Refresh | reserve short/unknown/total |',
        '|---|---:|---|---|---|---|---|---|',
        *rows,
        '',
        'Reserve columns are auxiliary; a shortfall is not an official deadline miss.',
        'An incomplete run keeps the declared denominator 64 Expert / 64 Cycle / 32 Refresh.',
        ''])
    (B9 / 'CPU_PATHS.md').write_text(doc)
    print(doc)


if __name__ == '__main__':
    main()
