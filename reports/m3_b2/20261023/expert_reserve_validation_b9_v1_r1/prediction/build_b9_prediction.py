#!/usr/bin/env python3
"""Freeze the B9-r1 pre-run prediction and the per-budget selection record.

Reads only the frozen B8 evidence and the frozen revision-r1 rule; never a B9
measurement.  The complete per-job prediction (Expert/Context/Cycle/Refresh x
typical/stress) is generated by ``prediction_model.build`` so the same code can
also补齐 a missing field at evaluation time.
"""
from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
B9 = HERE.parent
DAY = B9.parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(DAY / 'expert_reserve_selector_v1_r1' / 'ers'))

import prediction_model as pm      # noqa: E402
import common as ers_common        # noqa: E402
import rules as ers_rules          # noqa: E402

PROTOCOL = 'm3_b9_expert_reserve_validation_v1'
RULES_PATH = DAY / 'expert_reserve_selector_v1_r1' / 'RULES.json'
COSTS_PATH = DAY / 'expert_reserve_selector_v1_r1' / 'COSTS.json'
CONFIG_PATH = B9 / 'deployment' / 'CONFIG.json'


def sha(path):
    h = hashlib.sha256()
    with Path(path).open('rb') as f:
        for chunk in iter(lambda: f.read(8 * 1024 * 1024), b''):
            h.update(chunk)
    return h.hexdigest()


def canonical_sha(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':'),
                                      ensure_ascii=False).encode()).hexdigest()


def main():
    result = ers_common.rbe_env.load(ers_common.rbe_env.B8_RESULT)
    rules_doc = json.loads(RULES_PATH.read_text())
    rules_doc['_sha256'] = sha(RULES_PATH)
    costs_doc = json.loads(COSTS_PATH.read_text())
    costs_doc['_sha256'] = sha(COSTS_PATH)
    pred = pm.build(result, rules_doc, costs_doc, None, ers_rules.RE_MS)
    pred['protocol'] = PROTOCOL
    pred['fingerprint'] = canonical_sha({k: v for k, v in pred.items()
                                        if k != 'fingerprint'})
    (HERE / 'PREDICTION.json').write_text(json.dumps(pred, indent=2, sort_keys=True) + '\n')

    freeze = dict(
        schema='m3_b9_selection_freeze_v2', protocol=PROTOCOL,
        status='FROZEN_BEFORE_RUN', rule_id=rules_doc['id'],
        rule_sha256=rules_doc['_sha256'], costs_sha256=costs_doc['_sha256'],
        reserve_ms=ers_rules.RE_MS,
        by_period_ns={str(int(period * 1e6)): pred['selection']['p%d' % int(period)]
                      for period in ers_common.PERIODS_MS},
        note='recorded before each segment; it does not change the executed plan')
    freeze['fingerprint'] = canonical_sha(freeze)
    (HERE / 'SELECTION_FREEZE.json').write_text(
        json.dumps(freeze, indent=2, sort_keys=True) + '\n')

    rows = ['# B9-r1 pre-run prediction (frozen before any B9 measurement)', '',
            'Protocol `%s`; rule `%s`; RE = %g ms; %d job rows.' % (
                PROTOCOL, rules_doc['id'], ers_rules.RE_MS, len(pred['jobs'])), '',
            '| budget | S0 | S10 | two MC/ME/MR | three MC/ME/MR |',
            '|---|---|---|---|---|']
    for key in ('p180', 'p140'):
        b = pred['budgets'][key]
        c2, c3 = b['candidates']['two_9_9'], b['candidates']['three_prefix_9_9']
        rows.append('| %s | %s | **%s** | %.3f/%.3f/%.3f | %.3f/%.3f/%.3f |' % (
            key, b['S0']['selected'], b['S10']['selected'],
            c2['MC'], c2['ME'], c2['MR'], c3['MC'], c3['ME'], c3['MR']))
    rows += ['', 'Per-job rows (Expert/Context/Cycle/Refresh x typical/stress) include release,',
             'deadline, dispatch, completion, response, margin, status, version and the time origin;',
             'dispatch order and release-boundary distances are in `PREDICTION.json`.', '']
    (HERE / 'PREDICTION.md').write_text('\n'.join(rows))

    print(json.dumps(dict(fingerprint=pred['fingerprint'], jobs=len(pred['jobs']),
                          boundary=len(pred['boundary']),
                          completeness=pm.completeness(pred),
                          selection=freeze['by_period_ns'],
                          prediction_sha=sha(HERE / 'PREDICTION.json'),
                          selection_sha=sha(HERE / 'SELECTION_FREEZE.json')), indent=2))


if __name__ == '__main__':
    main()
